/**
 * Merveil runtimes: Browser preview, Deno project export, WebAssembly sandbox
 */
export function buildBrowserPreview(files) {
  const html = files['index.html'];
  if (html) return html;
  // Minimal React-less fallback from App.tsx text content
  const app = files['src/App.tsx'] || files['src/App.jsx'] || '';
  const css = files['src/styles.css'] || files['src/App.css'] || '';
  return `<!doctype html><html><head><meta charset="utf-8"/><meta name="viewport" content="width=device-width,initial-scale=1"/>
<style>body{font-family:system-ui;margin:0;padding:20px;background:#f7f4ef;color:#1a1a1a}${css}</style></head>
<body>
<div id="root"><pre style="white-space:pre-wrap;font-size:12px;opacity:.7">Open src/App.tsx in the editor. Browser preview works best with index.html starters.\n\n${escapeHtml(app.slice(0, 2000))}</pre></div>
</body></html>`;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

/** Package project for Deno (Deno.serve compatible static + optional handler) */
export function toDenoProject(files, name = 'merveil-app') {
  const out = { ...files };
  out['deno.json'] = JSON.stringify({
    name,
    tasks: {
      start: 'deno run -A server.ts',
      check: 'deno check server.ts',
    },
    compilerOptions: { lib: ['deno.window', 'dom'] },
  }, null, 2);
  out['server.ts'] = `// Deno server — generated by Merveil Pro Studio
import { serveDir } from "https://deno.land/std@0.224.0/http/file_server.ts";

const STATIC = new Map<string, string>([
${Object.entries(files)
  .filter(([p]) => !p.endsWith('.ts') || p.includes('src/'))
  .slice(0, 40)
  .map(([p, c]) => {
    const path = '/' + String(p).replace(/^\/+/, '');
    return '  [' + JSON.stringify(path) + ', ' + JSON.stringify(c) + '],';
  })
  .join('\n')}
]);

Deno.serve({ port: 8000 }, (req) => {
  const url = new URL(req.url);
  let path = url.pathname === "/" ? "/index.html" : url.pathname;
  if (STATIC.has(path)) {
    const body = STATIC.get(path)!;
    const type = path.endsWith(".html") ? "text/html"
      : path.endsWith(".css") ? "text/css"
      : path.endsWith(".js") || path.endsWith(".ts") ? "text/javascript"
      : path.endsWith(".json") ? "application/json"
      : "text/plain";
    return new Response(body, { headers: { "content-type": type } });
  }
  return new Response("Not found", { status: 404 });
});

console.log("Deno server http://localhost:8000");
`;
  out['README.deno.md'] = `# Deno run

\`\`\`bash
deno task start
# or
deno run -A server.ts
\`\`\`

Deploy: \`deno deploy --project=${name} server.ts\` (requires Deno Deploy token).
`;
  return out;
}

/**
 * Tiny WASM sandbox — validates numeric/string ops without native compile.
 * For real WASM, user exports .wasm; here we provide a JS-emulated module interface
 * and optional instantiate from base64 if files contain *.wasm (base64).
 */
export async function runWasmSandbox(files, input = {}) {
  const errors = [];
  const logs = [];
  const wasmKey = Object.keys(files).find((k) => k.endsWith('.wasm'));
  if (wasmKey) {
    try {
      const b64 = files[wasmKey].replace(/^data:.*base64,/, '').trim();
      const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
      const { instance } = await WebAssembly.instantiate(bin, {
        env: {
          log: (p) => logs.push('wasm log ptr ' + p),
        },
      });
      const exp = instance.exports;
      logs.push('WASM exports: ' + Object.keys(exp).join(', '));
      if (typeof exp.main === 'function') {
        const r = exp.main();
        logs.push('main() → ' + r);
      } else if (typeof exp._start === 'function') {
        exp._start();
        logs.push('_start() ok');
      }
      return { ok: true, logs, exports: Object.keys(exp) };
    } catch (e) {
      errors.push(e.message || String(e));
      return { ok: false, logs, errors };
    }
  }

  // Emulated "algorithm" module for demos (no .wasm file)
  const memory = new WebAssembly.Memory({ initial: 1 });
  const mod = {
    memory,
    add(a, b) { return (a | 0) + (b | 0); },
    hash(str) {
      let h = 2166136261;
      for (let i = 0; i < str.length; i++) {
        h ^= str.charCodeAt(i);
        h = Math.imul(h, 16777619);
      }
      return h >>> 0;
    },
    sortNums(arr) {
      return [...arr].map(Number).sort((a, b) => a - b);
    },
  };
  const a = Number(input.a ?? 2);
  const b = Number(input.b ?? 3);
  logs.push(`wasm-sandbox add(${a},${b}) = ${mod.add(a, b)}`);
  if (input.text) logs.push(`hash("${input.text}") = ${mod.hash(String(input.text))}`);
  logs.push('No .wasm file in project — ran JS-emulated sandbox (add algorithms under runtime).');
  return { ok: true, logs, errors, emulated: true, exports: Object.keys(mod) };
}

export function collectProjectErrors(files) {
  const errors = [];
  if (!files || !Object.keys(files).length) {
    errors.push({ level: 'error', msg: 'Project has no files' });
    return errors;
  }
  if (!files['package.json'] && !files['deno.json'] && !files['index.html']) {
    errors.push({ level: 'warn', msg: 'Missing package.json / deno.json / index.html' });
  }
  for (const [path, content] of Object.entries(files)) {
    if (typeof content !== 'string') {
      errors.push({ level: 'error', msg: `${path}: content is not a string` });
      continue;
    }
    if (path.endsWith('.json')) {
      try { JSON.parse(content); }
      catch (e) { errors.push({ level: 'error', msg: `${path}: ${e.message}` }); }
    }
    if (/\.(tsx?|jsx?)$/.test(path)) {
      const open = (content.match(/\{/g) || []).length;
      const close = (content.match(/\}/g) || []).length;
      if (Math.abs(open - close) > 2) {
        errors.push({ level: 'warn', msg: `${path}: brace imbalance ({ ${open} vs } ${close})` });
      }
      if (/console\.error\(|throw new Error/.test(content)) {
        errors.push({ level: 'info', msg: `${path}: contains explicit error throws / console.error` });
      }
    }
  }
  return errors;
}
